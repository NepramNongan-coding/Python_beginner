# to calculate the total no. of days to complete a job by three persons A,B and C
x = int(input("Enter the number of days to complete the job by the person A:"))
y = int(input("Enter the number of days to complete the job by the person B:"))
z = int(input("Enter the number of days to complete the job by the person C:"))

days = x+y+z

print("The total number of days to complete the job is",days)